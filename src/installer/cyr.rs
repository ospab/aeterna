/*
 * Installer — Cyrillic glyphs.
 *
 * The kernel font (arch/x86_64/font.rs) covers ASCII only. For the Russian installer UI this
 * module draws the Cyrillic letters itself, in the same 8x16 grid and VGA style. Letters that
 * look like a Latin letter reuse its glyph; the rest are listed below as (first row, row bytes).
 */

use ospab_os::arch::x86_64::{font, framebuffer};

pub fn is_cyrillic(c: char) -> bool {
    matches!(c as u32, 0x0410..=0x044F | 0x0401 | 0x0451)
}

/// Latin letter with the same shape.
fn lookalike(c: char) -> Option<char> {
    Some(match c {
        'А' => 'A', 'В' => 'B', 'Е' => 'E', 'К' => 'K', 'М' => 'M', 'Н' => 'H', 'О' => 'O',
        'Р' => 'P', 'С' => 'C', 'Т' => 'T', 'Х' => 'X',
        'а' => 'a', 'е' => 'e', 'о' => 'o', 'р' => 'p', 'с' => 'c', 'у' => 'y', 'х' => 'x',
        _ => return None,
    })
}

