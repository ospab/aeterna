fn bitmap(c: char) -> [u8; 16] {
    let mut g = [0u8; 16];
    let base = |l: char| *font::get_char_bitmap(l).unwrap();
    if let Some(l) = lookalike(c) { return base(l); }
    if c == 'Ё' || c == 'ё' {
        g = base(if c == 'Ё' { 'E' } else { 'e' });
        let r = if c == 'Ё' { 0 } else { 2 };
        g[r] |= 0x66;
        return g;
    }
    if let Some((top, rows)) = rows_of(c) {
        for (i, b) in rows.iter().enumerate() { if top + i < 16 { g[top + i] = *b; } }
        return g;
    }
    base('?')
}

/// Draw one Cyrillic letter at pixel (x, y).
pub fn draw(x: u64, y: u64, c: char, fg: u32, bg: u32) {
    let g = bitmap(c);
    let s = framebuffer::scale();
    framebuffer::fill_rect(x, y, 8 * s, 16 * s, bg);
    for (row, bits) in g.iter().enumerate() {
        let mut col = 0u64;
        while col < 8 {
            if bits & (0x80 >> col) != 0 {
                let start = col;
                while col < 8 && bits & (0x80 >> col) != 0 { col += 1; }
                framebuffer::fill_rect(x + start * s, y + row as u64 * s, (col - start) * s, s, fg);
            } else {
                col += 1;
            }
        }
    }
}
