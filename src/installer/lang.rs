/*
 * Installer — interface language.
 *
 * Every fixed text of the installer is an English string. `tr` returns the Russian text of the
 * same string when Russian is selected and the string itself otherwise (also for strings that are
 * not in the table). `Pen::put` runs every text through `tr`, so most screens need no extra code.
 * The Cyrillic letters are drawn by cyr.rs.
 */

use core::sync::atomic::{AtomicUsize, Ordering};

static LANG: AtomicUsize = AtomicUsize::new(0);

pub fn set(lang: usize) { LANG.store(lang, Ordering::Relaxed); }
pub fn is_ru() -> bool { LANG.load(Ordering::Relaxed) == 1 }

pub fn tr<'a>(s: &'a str) -> &'a str {
    if !is_ru() { return s; }
    for (en, ru) in RU {
        if *en == s { return ru; }
    }
    s
}

