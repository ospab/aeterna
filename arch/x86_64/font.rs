/// Get glyph bitmap for a character (8x16, one byte per row, MSB left).
/// Covers ASCII 32..127 plus `EXTRA_GLYPHS`; anything else renders as '?'.
#[inline]
pub fn get_char_bitmap(c: char) -> Option<&'static [u8; 16]> {
    let code = c as u32;
    if code >= 32 && code <= 127 {
        return Some(&FONT_8X16[(code - 32) as usize]);
    }
    for (ch, glyph) in EXTRA_GLYPHS {
        if *ch == c {
            return Some(glyph);
        }
    }
    Some(&FONT_8X16[('?' as u32 - 32) as usize])
}
